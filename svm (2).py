plt.xlabel("C (log scale)")
plt.ylabel("Fraction of support vectors")
plt.title("How many points define the boundary vs. C")
plt.tight_layout()
plt.show()

"""## How to read this

- SVs (support vectors): training points that lie on or inside the margin. They are the only points that affect the learned hyperplane.

- on_margin: |score| ≈ 1 → exactly on the margin.

- inside: |score| < 1 → margin violators (slack) — either misclassified or correctly classified but within the margin.

Trend you’ll usually see:

- As C increases, the model penalizes violations more → it pushes to separate harder → typically fewer support vectors overall, and fewer inside-margin violators.

- As C decreases (strong regularization), the margin gets “softer” → more points become support vectors, with more violators, and accuracy can drop (underfitting).

# 2: Move from a linear SVM to one that's capable of non-linear classification using kernels. Test the gaussian kernel function. Comment the results.

Note:
- Smaller σ ⇒ larger γ ⇒ very narrow kernels (highly local influence).
- Larger σ ⇒ smaller γ ⇒ wide kernels (smoother influence).

γ = = 1/2σ^2
"""

