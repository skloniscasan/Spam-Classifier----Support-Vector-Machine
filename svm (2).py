import numpy as np
from sklearn import svm

results = []

for C in [0.01, 0.03, 0.1, 0.3, 1, 3, 10, 30, 100]:
    clf = make_pipeline(StandardScaler(), svm.SVC(C=C, kernel='linear'))
    clf.fit(X1, y1)

    # Basic counts
    n_total = X1.shape[0]
    n_sv_total = clf.support_.size              # total support vectors
    n_sv_by_class = clf.n_support_              # [n_neg, n_pos] typically
    frac_sv = n_sv_total / n_total

    # Margin status of the support vectors
    scores_sv = clf.decision_function(X1[clf.support_])
    # In theory: |score| = 1 -> exactly on margin; <1 -> inside margin (slack)
    on_margin = np.isclose(np.abs(scores_sv), 1.0, atol=1e-6).sum()
    inside_margin = (np.abs(scores_sv) < 1 - 1e-6).sum()  # slack violators

    acc = clf.score(X1, y1)

    results.append({
        "C": C,
        "acc": acc,
        "n_sv_total": int(n_sv_total),
        "n_sv_neg": int(n_sv_by_class[0]),
        "n_sv_pos": int(n_sv_by_class[1]),
        "frac_sv": frac_sv,
        "on_margin": int(on_margin),
        "inside_margin": int(inside_margin),
    })

# Pretty print
print(f"{'C':>6}  {'acc':>6}  {'SVs':>5}  {'neg':>4}  {'pos':>4}  {'SV%':>6}  {'on|margin':>10}  {'inside':>6}")
for r in results:
    print(f"{r['C']:>6}  {r['acc']:>6.3f}  {r['n_sv_total']:>5}  {r['n_sv_neg']:>4}  {r['n_sv_pos']:>4}  "
          f"{100*r['frac_sv']:>5.1f}%  {r['on_margin']:>10}  {r['inside_margin']:>6}")

import matplotlib.pyplot as plt

Cs = [r["C"] for r in results]
