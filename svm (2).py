# ----- Visual confusion matrices -----
labels = np.unique(np.concatenate([yte, yhat]))  # typically [0,1]
ticklabels = ['Ham' if l==0 else 'Spam' for l in labels]

def plot_cm(matrix, title, fmt='d'):
    fig, ax = plt.subplots(figsize=(4.8, 4))
    im = ax.imshow(matrix, interpolation='nearest')
    ax.figure.colorbar(im, ax=ax)
    ax.set(xticks=np.arange(len(labels)), yticks=np.arange(len(labels)),
           xticklabels=ticklabels, yticklabels=ticklabels,
           xlabel='Predicted label', ylabel='True label', title=title)
    thresh = matrix.max() / 2.0
    for i in range(matrix.shape[0]):
        for j in range(matrix.shape[1]):
            ax.text(j, i, format(matrix[i, j], fmt),
                    ha='center', va='center',
                    color='white' if matrix[i, j] > thresh else 'black')
    plt.tight_layout(); plt.show()

# Raw counts
plot_cm(cm, 'Confusion Matrix (Counts)', fmt='d')

# Row-normalized
cm_norm = cm.astype(float) / cm.sum(axis=1, keepdims=True)
plot_cm(np.round(cm_norm, 2), 'Confusion Matrix (Row-Normalized)', fmt='.2f')

